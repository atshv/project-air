#!/usr/bin/env node
// Deterministic contract code generator.
//
// Reads the JSON Schema files under `schemas/` and writes two committed files:
//   generated/types.ts   TypeScript entity interfaces, enums, operation union
//                        and the embedded inverse pair
//   generated/contract.h C++20 structs/enums for the same model, one namespace
//
// Node.js builtins only. Stable ordering (schemas, properties, enums, union
// members sorted), LF endings, a generated-file banner and no timestamps or
// absolute paths, so two runs over the same schemas produce identical bytes.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const PACKAGE_DIR = dirname(fileURLToPath(import.meta.url));
export const CONTRACT_VERSION = "0.4.0";
export const GENERATED_FILES = ["types.ts", "contract.h"];
export const GENERATED_DIR = join(PACKAGE_DIR, "generated");

const SCHEMA_DIR = join(PACKAGE_DIR, "schemas");
const BANNER = "Generated by codegen.mjs from packages/contracts/schemas. Do not edit by hand.";
const NAMESPACE = "project_air::contracts";
const CPP_KEYWORDS = new Set([
  "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break",
  "case", "catch", "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept",
  "const", "consteval", "constexpr", "constinit", "const_cast", "continue", "co_await",
  "co_return", "co_yield", "decltype", "default", "delete", "do", "double", "dynamic_cast",
  "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto",
  "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
  "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register",
  "reinterpret_cast", "requires", "return", "short", "signed", "sizeof", "static",
  "static_assert", "static_cast", "struct", "switch", "template", "this", "thread_local",
  "throw", "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
  "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
]);

/** PascalCase for a kebab-case or camelCase name. */
function pascal(name) {
  return String(name)
    .split(/[^0-9A-Za-z]+/)
    .filter((part) => part.length > 0)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function compareStrings(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function upperSnake(name) {
  return String(name).replace(/(?<!^)(?=[A-Z])/g, "_").toUpperCase();
}

function sortedUnique(values) {
  return [...new Set(values)].sort(compareStrings);
}

function cppEnumValue(value) {
  const cleaned = String(value).replace(/[^0-9A-Za-z_]/g, "_");
  const identifier = /^[A-Za-z_]/.test(cleaned) ? cleaned : `_${cleaned}`;
  return CPP_KEYWORDS.has(identifier) ? `${identifier}_` : identifier;
}

function loadSchemas() {
  const files = readdirSync(SCHEMA_DIR)
    .filter((file) => file.endsWith(".schema.json"))
    .sort(compareStrings);
  const schemas = new Map();
  for (const file of files) {
    schemas.set(file.replace(/\.schema\.json$/, ""), JSON.parse(readFileSync(join(SCHEMA_DIR, file), "utf8")));
  }
  return schemas;
}

const schemas = loadSchemas();
const operationSchema = schemas.get("operation");
if (operationSchema === undefined) throw new Error("schemas/operation.schema.json is missing");

// --- type registry ------------------------------------------------------------

const enumTypes = new Map(); // name -> sorted values
const enumBySignature = new Map(); // values signature -> name
const objectTypes = new Map(); // name -> { description, schema, fields }
let processedObjects = new Set();

function registerEnum(name, values) {
  const sorted = sortedUnique(values);
  const signature = sorted.join("|");
  const existing = enumBySignature.get(signature);
  if (existing !== undefined) return existing;
  if (enumTypes.has(name)) throw new Error(`duplicate enum name ${name}`);
  enumTypes.set(name, sorted);
  enumBySignature.set(signature, name);
  return name;
}

function enumNameHint(ownerName, propertyName) {
  const base = ownerName.endsWith("Payload") ? ownerName.slice(0, -"Payload".length) : ownerName;
  return `${base}${pascal(propertyName)}`;
}

function registerObject(name, schema, description) {
  if (objectTypes.has(name)) return name;
  objectTypes.set(name, { name, schema, description: description ?? schema.description ?? "", fields: [] });
  processedObjects = new Set([...processedObjects].filter((entry) => entry !== name));
  return name;
}

const ENTITY_NAMES = new Map(); // schema key -> type name
for (const [key, schema] of schemas) {
  if (key === "operation") continue;
  ENTITY_NAMES.set(key, pascal(key));
}
const ENTITY_ORDER = [...ENTITY_NAMES.entries()].sort((a, b) => compareStrings(a[1], b[1]));

// Local `$defs` of the 0.4.0 note body document collide with the board entity
// type names (`block` is both a canvas block entity and a note body block). The
// note body keeps the contract schema names but its generated types are scoped
// to `NoteBody*`, so `NoteBodyPayload.blocks` is the editor document block and
// not the canvas `Block` entity.
const DEF_NAME_OVERRIDES = {
  "note-body-payload": { block: "NoteBodyBlock" },
};

for (const [key, name] of ENTITY_ORDER) {
  const schema = schemas.get(key);
  registerObject(name, schema, schema.description);
  const overrides = DEF_NAME_OVERRIDES[key] ?? {};
  for (const [defKey, def] of Object.entries(schema.$defs ?? {})) {
    if (def.type === "object") registerObject(overrides[defKey] ?? pascal(defKey), def, def.description);
  }
}

const operationDefs = operationSchema.$defs ?? {};
registerEnum("OperationType", operationDefs.operationType.enum);

const payloadTypeByDefKey = new Map();
const payloadDefs = Object.entries(operationDefs)
  .filter(([key]) => key.startsWith("payload-"))
  .sort((a, b) => compareStrings(a[0], b[0]));
for (const [key, def] of payloadDefs) {
  const typeName = `${pascal(key.replace(/^payload-/, ""))}Payload`;
  payloadTypeByDefKey.set(key, typeName);
  registerObject(typeName, def, def.description);
}
registerObject("GroupPayload", operationDefs["group-payload"], operationDefs["group-payload"].description);
registerObject("GroupInversePayload", operationDefs["group-inverse-payload"], operationDefs["group-inverse-payload"].description);

const LOCAL_REF_NAMES = {
  "#/$defs/operation": "Operation",
  "#/$defs/inverse": "OperationInverse",
  "#/$defs/child-operation": "Operation",
  "#/$defs/group-payload": "GroupPayload",
  "#/$defs/group-inverse-payload": "GroupInversePayload",
  "#/$defs/operationType": "OperationType",
  // The only local `block` definition is the note body block of
  // note-body-payload.schema.json; see DEF_NAME_OVERRIDES above.
  "#/$defs/block": "NoteBodyBlock",
};

function refTypeName(ref) {
  if (LOCAL_REF_NAMES[ref] !== undefined) return LOCAL_REF_NAMES[ref];
  if (ref.startsWith("#/$defs/payload-")) {
    const key = ref.slice("#/$defs/".length);
    const name = payloadTypeByDefKey.get(key);
    if (name === undefined) throw new Error(`unknown payload ref ${ref}`);
    return name;
  }
  if (ref.startsWith("#/$defs/")) return pascal(ref.slice("#/$defs/".length));
  return entityTypeName(ref);
}

function entityTypeName(refFile) {
  const name = String(refFile).replace(/\.schema\.json$/, "");
  const typeName = ENTITY_NAMES.get(name);
  if (typeName === undefined) throw new Error(`unknown schema $ref ${refFile}`);
  return typeName;
}

/** The TypeScript and C++ type for one property schema. */
function typeOf(schema, ownerName, propertyName) {
  if (schema === null || typeof schema !== "object") return { ts: "unknown", cpp: "std::string", nullable: false, ref: null };
  if (typeof schema.$ref === "string") {
    return { ts: refTypeName(schema.$ref), cpp: refTypeName(schema.$ref), nullable: false, ref: refTypeName(schema.$ref) };
  }
  if (Array.isArray(schema.enum)) {
    const name = registerEnum(enumNameHint(ownerName, propertyName), schema.enum);
    return { ts: name, cpp: name, nullable: false, ref: name };
  }
  if (schema.const !== undefined) {
    const literal = JSON.stringify(schema.const);
    return { ts: literal, cpp: "std::string", nullable: false, ref: null };
  }
  if (Array.isArray(schema.type)) {
    const nullable = schema.type.includes("null");
    const nonNull = schema.type.filter((entry) => entry !== "null");
    if (nonNull.length === 1) {
      const inner = typeOf({ ...schema, type: nonNull[0] }, ownerName, propertyName);
      return { ...inner, nullable: nullable || inner.nullable };
    }
    const members = nonNull.map((entry) => typeOf({ ...schema, type: entry }, ownerName, propertyName));
    return {
      ts: members.map((member) => member.ts).join(" | ") + (nullable ? " | null" : ""),
      cpp: members[0] === undefined ? "std::string" : members[0].cpp,
      nullable,
      ref: null,
    };
  }
  switch (schema.type) {
    case "string":
      return { ts: "string", cpp: "std::string", nullable: false, ref: null };
    case "number":
    case "integer":
      return { ts: "number", cpp: "double", nullable: false, ref: null };
    case "boolean":
      return { ts: "boolean", cpp: "bool", nullable: false, ref: null };
    case "null":
      return { ts: "null", cpp: "std::nullptr_t", nullable: true, ref: null };
    case "array": {
      let items;
      if (schema.items?.type === "object" && schema.items.$ref === undefined) {
        const itemName = registerObjectType(
          `${ownerName}${pascal(propertyName)}Item`,
          schema.items,
          ownerName,
          propertyName,
        );
        items = { ts: itemName, cpp: itemName };
      } else {
        items = typeOf(schema.items ?? {}, ownerName, `${propertyName}Item`);
      }
      const ts = items.ts.includes(" | ") ? `(${items.ts})[]` : `${items.ts}[]`;
      return { ts, cpp: `std::vector<${items.cpp}>`, nullable: false, ref: null };
    }
    case "object": {
      const typeName = `${ownerName}${pascal(propertyName)}`;
      return { ts: registerObjectType(typeName, schema, ownerName, propertyName), cpp: typeName, nullable: false, ref: typeName };
    }
    default:
      return { ts: "unknown", cpp: "std::string", nullable: false, ref: null };
  }
}

function registerObjectType(name, schema, ownerName, propertyName) {
  if (objectTypes.has(name)) return name;
  registerObject(name, schema, `Inline object of ${ownerName}.${propertyName}.`);
  return name;
}

function convertObject(type) {
  const required = new Set(type.schema.required ?? []);
  const properties = type.schema.properties ?? {};
  const fields = [];
  for (const propertyName of Object.keys(properties).sort(compareStrings)) {
    const property = properties[propertyName];
    const resolved = typeOf(property, type.name, propertyName);
    fields.push({ name: propertyName, required: required.has(propertyName), ...resolved });
  }
  type.fields = fields;
}

function drainRegistry() {
  for (;;) {
    const pending = [...objectTypes.keys()].filter((name) => !processedObjects.has(name)).sort(compareStrings);
    if (pending.length === 0) return;
    for (const name of pending) {
      processedObjects.add(name);
      convertObject(objectTypes.get(name));
    }
  }
}
drainRegistry();

// --- dependency ordering for the C++ struct definitions ----------------------

const SPECIAL_CPP = new Set(["GroupPayload", "GroupInversePayload", "Operation", "OperationInverse"]);

function structDependencies(typeName) {
  const type = objectTypes.get(typeName);
  const dependencies = new Set();
  const collect = (text) => {
    for (const match of String(text).matchAll(/[A-Z][0-9A-Za-z]*/g)) {
      if (objectTypes.has(match[0]) && match[0] !== typeName) dependencies.add(match[0]);
    }
  };
  for (const field of type.fields) collect(field.cpp);
  return dependencies;
}

function cppDefinitionOrder() {
  const order = [];
  const visiting = new Set();
  const visited = new Set();
  const visit = (name) => {
    if (visited.has(name) || SPECIAL_CPP.has(name)) return;
    if (visiting.has(name)) return; // defensive: cycles do not occur outside the operation envelope
    visiting.add(name);
    for (const dependency of [...structDependencies(name)].sort(compareStrings)) visit(dependency);
    visiting.delete(name);
    visited.add(name);
    order.push(name);
  };
  for (const name of [...objectTypes.keys()].sort(compareStrings)) visit(name);
  return order;
}

// --- operation branches -------------------------------------------------------

function branchPayloadType(branch) {
  const ref = branch.then?.properties?.payload?.$ref;
  if (typeof ref !== "string") throw new Error("operation branch without payload $ref");
  return refTypeName(ref);
}

function operationBranches() {
  return operationDefs.operation.allOf
    .map((branch) => ({ type: branch.if.properties.type.const, payload: branchPayloadType(branch) }))
    .sort((a, b) => compareStrings(a.type, b.type));
}

function inverseBranches() {
  return operationDefs.inverse.allOf
    .map((branch) => ({ type: branch.if.properties.type.const, payload: branchPayloadType(branch) }))
    .sort((a, b) => compareStrings(a.type, b.type));
}

// --- TypeScript ---------------------------------------------------------------

function renderTypeScript() {
  const lines = [
    `// ${BANNER}`,
    `// Contract version: ${CONTRACT_VERSION}`,
    "",
    `export const CONTRACT_VERSION = "${CONTRACT_VERSION}" as const;`,
    "",
    `export type ContractVersion = "${CONTRACT_VERSION}";`,
    "",
  ];

  for (const name of [...enumTypes.keys()].sort(compareStrings)) {
    const values = enumTypes.get(name);
    if (name === "OperationType") {
      lines.push(`export type OperationType = ${values.map((value) => `"${value}"`).join(" | ")};`);
      lines.push(`export const OPERATION_TYPES = [${values.map((value) => `"${value}"`).join(", ")}] as const;`);
    } else {
      lines.push(`export type ${name} = ${values.map((value) => `"${value}"`).join(" | ")};`);
      lines.push(`export const ${upperSnake(name)}_VALUES = [${values.map((value) => `"${value}"`).join(", ")}] as const;`);
    }
    lines.push("");
  }

  for (const name of [...objectTypes.keys()].sort(compareStrings)) {
    const type = objectTypes.get(name);
    lines.push(`export interface ${name} {`);
    for (const field of type.fields) {
      const optional = field.required ? "" : "?";
      const ts = field.nullable && !field.ts.includes("null") ? `${field.ts} | null` : field.ts;
      lines.push(`  ${field.name}${optional}: ${ts};`);
    }
    lines.push("}");
    lines.push("");
  }

  const operationUnion = operationBranches()
    .map((branch) => `  | { payload: ${branch.payload}; type: "${branch.type}" }`)
    .join("\n");
  const inverseUnion = inverseBranches()
    .map((branch) => `  | { payload: ${branch.payload}; type: "${branch.type}" }`)
    .join("\n");

  lines.push("export type Operation = {");
  lines.push("  actorId: string;");
  lines.push("  boardId: string;");
  lines.push("  createdAt: string;");
  lines.push("  id: string;");
  lines.push("  inverse: OperationInverse;");
  lines.push("} & (");
  lines.push(operationUnion);
  lines.push(");");
  lines.push("");
  lines.push("export type OperationInverse = {");
  lines.push("  boardId: string;");
  lines.push("} & (");
  lines.push(inverseUnion);
  lines.push(");");
  lines.push("");
  lines.push(`export type OperationPayload = ${[...new Set(operationBranches().map((branch) => branch.payload))].sort(compareStrings).join(" | ")};`);
  lines.push(`export type OperationInversePayload = ${[...new Set(inverseBranches().map((branch) => branch.payload))].sort(compareStrings).join(" | ")};`);
  lines.push("");

  return `${lines.join("\n")}\n`;
}

// --- C++ ----------------------------------------------------------------------

function cppFieldType(field) {
  const base = field.cpp;
  const needsOptional = !field.required || field.nullable;
  if (!needsOptional) return base;
  if (base.startsWith("std::optional<") || base === "std::nullptr_t") return base;
  return `std::optional<${base}>`;
}

function renderCpp() {
  const lines = [
    `// ${BANNER}`,
    `// Contract version: ${CONTRACT_VERSION}`,
    "#pragma once",
    "",
    "#include <optional>",
    "#include <string>",
    "#include <variant>",
    "#include <vector>",
    "",
    `namespace ${NAMESPACE} {`,
    "",
    `inline constexpr const char* kContractVersion = "${CONTRACT_VERSION}";`,
    "",
  ];

  for (const name of [...enumTypes.keys()].sort(compareStrings)) {
    const values = enumTypes.get(name).map(cppEnumValue);
    lines.push(`enum class ${name} { ${values.join(", ")} };`);
  }
  lines.push("");

  for (const name of cppDefinitionOrder()) {
    const type = objectTypes.get(name);
    lines.push(`struct ${name} {`);
    for (const field of type.fields) lines.push(`  ${cppFieldType(field)} ${field.name};`);
    lines.push("};");
    lines.push("");
  }

  lines.push("struct Operation;");
  lines.push("struct OperationInverse;");
  lines.push("");
  for (const name of ["GroupPayload", "GroupInversePayload"]) {
    const type = objectTypes.get(name);
    lines.push(`struct ${name} {`);
    for (const field of type.fields) lines.push(`  ${cppFieldType(field)} ${field.name};`);
    lines.push("};");
    lines.push("");
  }

  const operationAlternatives = sortedUnique(operationBranches().map((branch) => branch.payload));
  const inverseAlternatives = sortedUnique(inverseBranches().map((branch) => branch.payload));
  lines.push(`using OperationPayload = std::variant<${operationAlternatives.join(", ")}>;`);
  lines.push(`using OperationInversePayload = std::variant<${inverseAlternatives.join(", ")}>;`);
  lines.push("");
  lines.push("struct OperationInverse {");
  lines.push("  std::string boardId;");
  lines.push("  OperationInversePayload payload;");
  lines.push("  OperationType type;");
  lines.push("};");
  lines.push("");
  lines.push("struct Operation {");
  lines.push("  std::string actorId;");
  lines.push("  std::string boardId;");
  lines.push("  std::string createdAt;");
  lines.push("  std::string id;");
  lines.push("  OperationInverse inverse;");
  lines.push("  OperationPayload payload;");
  lines.push("  OperationType type;");
  lines.push("};");
  lines.push("");
  lines.push(`}  // namespace ${NAMESPACE}`);
  lines.push("");

  return `${lines.join("\n")}\n`;
}

/** Render both generated files, keyed by file name. */
export function generate() {
  return new Map([
    ["types.ts", renderTypeScript()],
    ["contract.h", renderCpp()],
  ]);
}

/** Write the generated files and return their paths relative to the package. */
export function writeGenerated() {
  mkdirSync(GENERATED_DIR, { recursive: true });
  const written = [];
  for (const [fileName, content] of generate()) {
    writeFileSync(join(GENERATED_DIR, fileName), content, "utf8");
    written.push(`generated/${fileName}`);
  }
  return written;
}

const isMain =
  process.argv[1] !== undefined && join(PACKAGE_DIR, "codegen.mjs") === join(process.argv[1]);

if (isMain) {
  const written = writeGenerated();
  process.stdout.write(`contracts codegen: wrote ${written.join(", ")}\n`);
}
