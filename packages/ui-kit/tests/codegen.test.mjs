// A2: codegen is deterministic and the committed tokens.css, tokens.h and
// layers.ts are exactly its derived output; every token appears with its value.

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

import {
  cppIdentifier,
  cppLiteral,
  cssValue,
  flattenLayers,
  flattenTokens,
  generate,
  readTokens,
  renderCss,
  renderHeader,
  renderLayers,
  writeGenerated,
} from "../codegen.mjs";
import { LAYERS, LAYER_ORDER, LAYER_Z_INDEX } from "../layers.ts";

const tokens = readTokens();
const read = (name) => readFileSync(new URL(`../${name}`, import.meta.url), "utf8");

test("committed tokens.css equals the generated CSS", () => {
  assert.equal(read("tokens.css"), renderCss(tokens));
});

test("committed tokens.h equals the generated C++ header", () => {
  const header = read("tokens.h");
  assert.equal(header, renderHeader(tokens));
  assert.ok(header.startsWith("// Generated by codegen.mjs from tokens.json. Do not edit by hand.\n#pragma once\n"));
  assert.ok(header.includes("namespace tokens {"));
  assert.ok(header.includes("}  // namespace tokens\n"));
});

test("committed layers.ts equals the generated layer order", () => {
  assert.equal(read("layers.ts"), renderLayers(tokens));
});

test("every token appears in the generated CSS with the token value", () => {
  const css = renderCss(tokens);
  for (const token of flattenTokens(tokens)) {
    assert.ok(
      css.includes(`  --${token.name}: ${cssValue(token.value)};`),
      `tokens.css contains --${token.name}`,
    );
  }
  assert.equal((css.match(/^ {2}--/gm) ?? []).length, flattenTokens(tokens).length);
  assert.ok(css.startsWith("/* Generated by codegen.mjs from tokens.json. Do not edit by hand. */\n\n:root {\n"));
  assert.ok(css.endsWith("}\n"));
});

test("every token appears in the generated C++ header with the token value", () => {
  const header = renderHeader(tokens);
  for (const token of flattenTokens(tokens)) {
    const { type, literal } = cppLiteral(token.value);
    const declaration =
      type === "string"
        ? `inline constexpr const char* ${cppIdentifier(token.name)} = ${literal};`
        : `inline constexpr ${type} ${cppIdentifier(token.name)} = ${literal};`;
    assert.ok(header.includes(declaration), `tokens.h contains ${cppIdentifier(token.name)}`);
  }
  assert.equal((header.match(/inline constexpr /g) ?? []).length, flattenTokens(tokens).length);
});

test("a second render is byte-identical (no timestamps, stable ordering)", () => {
  const first = generate();
  const second = generate();
  assert.deepEqual([...first.keys()], ["tokens.css", "tokens.h", "layers.ts"]);
  for (const [name, content] of first) {
    assert.equal(second.get(name), content, `${name} is stable`);
    assert.ok(!/\b(19|20)\d{2}-\d{2}-\d{2}\b/.test(content), `${name} carries no date`);
    assert.ok(!/\bgenerated (on|at) /i.test(content), `${name} carries no timestamp`);
  }
});

test("codegen.mjs uses Node builtins only", () => {
  const source = read("codegen.mjs");
  const specifiers = [...source.matchAll(/from\s+"([^"]+)"/g)].map((match) => match[1]);
  assert.ok(specifiers.length > 0);
  for (const specifier of specifiers) {
    assert.ok(specifier.startsWith("node:"), `only node: imports, found ${specifier}`);
  }
  assert.ok(!/\b(Date|new Date)\b/.test(source), "codegen reads no clock");
});

test("layers.ts data matches tokens.json", () => {
  const expected = flattenLayers(tokens);
  assert.deepEqual(
    LAYERS.map((layer) => ({ ...layer })),
    expected,
  );
  assert.deepEqual([...LAYER_ORDER], expected.map((layer) => layer.name));
  assert.deepEqual(
    { ...LAYER_Z_INDEX },
    Object.fromEntries(expected.map((layer) => [layer.name, layer.zIndex])),
  );
  const remote = LAYERS.findIndex((layer) => layer.name === "remote-cursors");
  assert.equal(LAYERS[remote].order, "7a");
  assert.equal(LAYERS[remote].zIndex, 7);
});

test("writeGenerated writes the three documented files", () => {
  assert.deepEqual(writeGenerated(), ["tokens.css", "tokens.h", "layers.ts"]);
});
