#!/usr/bin/env node
// Deterministic design-token code generator for packages/ui-kit.
//
// Reads tokens.json and writes three derived files:
//   tokens.css  the custom properties for the web app
//   tokens.h    the C++ header for the engine
//   layers.ts   the typed layer order for web and engine
//
// Node.js builtins only, stable ordering, LF endings and no timestamps, so two
// runs over the same tokens.json produce byte-identical output.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const PACKAGE_DIR = dirname(fileURLToPath(import.meta.url));

/** Value groups in generated output order; layers are handled separately. */
export const VALUE_GROUPS = [
  "colours",
  "spacing",
  "sizes",
  "radii",
  "typography",
  "motion",
  "shadows",
];

/** Generated files in write order. */
export const GENERATED_FILES = ["tokens.css", "tokens.h", "layers.ts"];

const BANNER = "Generated by codegen.mjs from tokens.json. Do not edit by hand.";

class TokenError extends Error {}

function fail(message) {
  throw new TokenError(`tokens.json: ${message}`);
}

/** Minimal structural validation; the unit tests check the design-law values. */
function validate(tokens) {
  if (tokens === null || typeof tokens !== "object" || Array.isArray(tokens)) {
    fail("the document must be an object");
  }
  const allowedKeys = new Set([...VALUE_GROUPS, "layers"]);
  for (const key of Object.keys(tokens)) {
    if (!allowedKeys.has(key)) {
      fail(`unexpected top-level key "${key}"; tokens.json carries token values only`);
    }
  }
  const names = new Set();
  for (const group of VALUE_GROUPS) {
    const entries = tokens[group];
    if (entries === null || typeof entries !== "object" || Array.isArray(entries)) {
      fail(`group "${group}" must be an object`);
    }
    for (const [name, value] of Object.entries(entries)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
        fail(`invalid token name "${name}" in group "${group}"`);
      }
      if (typeof value !== "string" && typeof value !== "number") {
        fail(`token "${name}" must be a string or a number`);
      }
      if (names.has(name)) fail(`duplicate token name "${name}"`);
      names.add(name);
    }
  }
  if (!Array.isArray(tokens.layers) || tokens.layers.length === 0) {
    fail("group \"layers\" must be a non-empty array");
  }
  const orders = new Set();
  for (const layer of tokens.layers) {
    if (layer === null || typeof layer !== "object") fail("every layer must be an object");
    if (typeof layer.name !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(layer.name)) {
      fail("every layer needs a kebab-case name");
    }
    if (typeof layer.order !== "string" || !/^\d+[a-z]?$/.test(layer.order)) {
      fail(`layer "${layer.name}" needs a layer order such as "7" or "7a"`);
    }
    if (!Number.isInteger(layer["z-index"]) || layer["z-index"] < 0) {
      fail(`layer "${layer.name}" needs an integer z-index`);
    }
    if (orders.has(layer.order)) fail(`duplicate layer order "${layer.order}"`);
    orders.add(layer.order);
    const tokenName = `layer-${layer.name}`;
    if (names.has(tokenName)) fail(`duplicate token name "${tokenName}"`);
    names.add(tokenName);
  }
}

/** Read and validate tokens.json. */
export function readTokens(packageDir = PACKAGE_DIR) {
  const tokens = JSON.parse(readFileSync(join(packageDir, "tokens.json"), "utf8"));
  validate(tokens);
  return tokens;
}

/** Flatten every token to `{ group, name, value }` in stable generated order. */
export function flattenTokens(tokens) {
  const entries = [];
  for (const group of VALUE_GROUPS) {
    for (const [name, value] of Object.entries(tokens[group])) {
      entries.push({ group, name, value });
    }
  }
  for (const layer of tokens.layers) {
    entries.push({ group: "layers", name: `layer-${layer.name}`, value: layer["z-index"] });
  }
  return entries;
}

/** The layers as `{ name, order, zIndex }`, bottom to top. */
export function flattenLayers(tokens) {
  return tokens.layers.map((layer) => ({
    name: layer.name,
    order: layer.order,
    zIndex: layer["z-index"],
  }));
}

/** The CSS value of a token: strings as authored, numbers without a unit. */
export function cssValue(value) {
  return String(value);
}

/** The C++ constant of a token: `{ type, literal }` with `int`, `double` or `string`. */
export function cppLiteral(value) {
  if (typeof value === "number") {
    return Number.isInteger(value)
      ? { type: "int", literal: String(value) }
      : { type: "double", literal: decimal(value) };
  }
  const text = String(value);
  const px = /^(-?\d+(?:\.\d+)?)px$/.exec(text);
  if (px) return { type: "double", literal: decimal(Number(px[1])) };
  const ms = /^(-?\d+(?:\.\d+)?)ms$/.exec(text);
  if (ms) return { type: "int", literal: String(Number(ms[1])) };
  const em = /^(-?\d+(?:\.\d+)?)em$/.exec(text);
  if (em) return { type: "double", literal: decimal(Number(em[1])) };
  return { type: "string", literal: cppString(text) };
}

function decimal(value) {
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function cppString(text) {
  return `"${text.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/** The C++ identifier for a CSS custom-property name. */
export function cppIdentifier(name) {
  return name.replaceAll("-", "_");
}

function groupComment(group) {
  return group === "layers" ? "layers (z-index)" : group;
}

/** Render tokens.css: `:root { --name: value; }`. */
export function renderCss(tokens) {
  const lines = [`/* ${BANNER} */`, "", ":root {"];
  let previousGroup = null;
  for (const token of flattenTokens(tokens)) {
    if (token.group !== previousGroup) {
      if (previousGroup !== null) lines.push("");
      lines.push(`  /* ${groupComment(token.group)} */`);
      previousGroup = token.group;
    }
    lines.push(`  --${token.name}: ${cssValue(token.value)};`);
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

/** Render tokens.h: `#pragma once` plus one typed constant per token. */
export function renderHeader(tokens) {
  const lines = [`// ${BANNER}`, "#pragma once", "", "namespace tokens {", ""];
  let previousGroup = null;
  for (const token of flattenTokens(tokens)) {
    if (token.group !== previousGroup) {
      if (previousGroup !== null) lines.push("");
      lines.push(`// ${groupComment(token.group)}`);
      previousGroup = token.group;
    }
    const { type, literal } = cppLiteral(token.value);
    const identifier = cppIdentifier(token.name);
    const declaration =
      type === "string"
        ? `inline constexpr const char* ${identifier} = ${literal};`
        : `inline constexpr ${type} ${identifier} = ${literal};`;
    lines.push(`${declaration}  // ${cssValue(token.value)}`);
  }
  lines.push("", "}  // namespace tokens");
  return `${lines.join("\n")}\n`;
}

/** Render layers.ts: the layer order and z-index values as typed data. */
export function renderLayers(tokens) {
  const layers = flattenLayers(tokens);
  const lines = [`// ${BANNER}`, "", "export const LAYERS = ["];
  for (const layer of layers) {
    lines.push(
      `  { name: ${JSON.stringify(layer.name)}, order: ${JSON.stringify(layer.order)}, zIndex: ${layer.zIndex} },`,
    );
  }
  lines.push("] as const;", "", "export type LayerName = (typeof LAYERS)[number][\"name\"];", "");
  lines.push("export type LayerZIndex = (typeof LAYERS)[number][\"zIndex\"];", "");
  const names = layers.map((layer) => JSON.stringify(layer.name)).join(", ");
  lines.push(`export const LAYER_ORDER: readonly LayerName[] = [${names}];`, "");
  lines.push("export const LAYER_Z_INDEX: Readonly<Record<LayerName, LayerZIndex>> = {");
  for (const layer of layers) {
    lines.push(`  ${JSON.stringify(layer.name)}: ${layer.zIndex},`);
  }
  lines.push(
    "};",
    "",
    "// Layer 7a (remote cursors) shares z-index 7 with snap guides and renders after them",
    "// through DOM/render order, so it stays between snap guides and canvas chrome.",
  );
  return `${lines.join("\n")}\n`;
}

/** Render every generated file, keyed by file name, in write order. */
export function generate(packageDir = PACKAGE_DIR) {
  const tokens = readTokens(packageDir);
  const output = new Map();
  output.set("tokens.css", renderCss(tokens));
  output.set("tokens.h", renderHeader(tokens));
  output.set("layers.ts", renderLayers(tokens));
  return output;
}

/** Write every generated file and return its path relative to the package. */
export function writeGenerated(packageDir = PACKAGE_DIR) {
  const output = generate(packageDir);
  const written = [];
  for (const [fileName, content] of output) {
    writeFileSync(join(packageDir, fileName), content, "utf8");
    written.push(fileName);
  }
  return written;
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const written = writeGenerated();
  process.stdout.write(`ui-kit codegen: wrote ${written.join(", ")}\n`);
}
