// Design rules gate: raw colours, off-grid spacing, layer z-index and UI evidence.
//
// The allowed values are read from the generated design source and are never
// duplicated here: packages/ui-kit/tokens.json (colours, spacing, sizes, radii)
// and packages/ui-kit/layers.ts (layer names, order and z-index values).

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { extname, join, relative } from "node:path";

/** Rule identifiers used in findings. */
export const RULES = Object.freeze({
  RAW_COLOUR: "raw-colour",
  OFF_GRID_SPACING: "off-grid-spacing",
  Z_INDEX: "z-index",
  MISSING_EVIDENCE: "missing-evidence",
});

/** Paths scanned by the gate, relative to the project root. */
export const SCAN_ROOTS = Object.freeze([
  "apps",
  "packages/ui-kit",
  "packages/editor",
  "packages/engine/src/render",
]);

/** The design source; both files are generated by packages/ui-kit/codegen.mjs. */
export const SOURCE_FILES = Object.freeze({
  tokens: "packages/ui-kit/tokens.json",
  layers: "packages/ui-kit/layers.ts",
});

/** File types that can carry visual values. */
export const SCAN_EXTENSIONS = Object.freeze(
  new Set([
    ".css",
    ".html",
    ".htm",
    ".ts",
    ".tsx",
    ".js",
    ".jsx",
    ".mjs",
    ".cjs",
    ".cc",
    ".cpp",
    ".h",
    ".hpp",
    ".svg",
  ]),
);

/** Directories never scanned, by directory name anywhere in the tree. */
export const IGNORED_DIRECTORIES = Object.freeze(
  new Set([
    "node_modules",
    ".git",
    ".turbo",
    "dist",
    "build",
    "coverage",
    "reference",
    "reviews",
    "docs",
    "fixtures",
    "test",
    "tests",
    "__tests__",
  ]),
);

/** Generated design source files: derived from tokens.json, never checked. */
export const IGNORED_FILES = Object.freeze(
  new Set([
    "packages/ui-kit/tokens.css",
    "packages/ui-kit/tokens.h",
    "packages/ui-kit/tokens.json",
    "packages/ui-kit/layers.ts",
  ]),
);

/** A configuration problem: missing or unreadable design source (exit code 2). */
export class ConfigError extends Error {
  constructor(message) {
    super(message);
    this.name = "ConfigError";
  }
}

const LAYER_ENTRY = /\{\s*name:\s*"([^"]+)",\s*order:\s*"([^"]+)",\s*zIndex:\s*(-?\d+)\s*\}/g;
const HEX_COLOUR = /(?<!&)(#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b)/g;
const FUNCTION_COLOUR = /\b(rgba?|hsla?)\(/gi;
const SPACING_PROPERTY =
  /(?<![-a-zA-Z0-9_])(margin|padding|gap|row-gap|column-gap|inset|top|right|bottom|left)(?:-(?:inline|block)(?:-(?:start|end))?)?\s*:\s*([^;{}"']+)/gi;
const Z_INDEX_PROPERTY = /(?<![-a-zA-Z0-9_])z-index\s*:\s*([^;{}"']+)/gi;
const NON_PX_UNIT = /(?:rem|em|ex|ch|vw|vh|vmin|vmax|cm|mm|in|pt|pc|q)$/i;
const KEYWORD_VALUE =
  /^(?:auto|inherit|initial|unset|revert|revert-layer|none|normal|transparent|currentcolor|center|top|bottom|left|right)$/i;

function readSource(root, path) {
  try {
    return readFileSync(join(root, path), "utf8");
  } catch {
    throw new ConfigError(`cannot read ${path}; run design-check from the repository root`);
  }
}

function pxValues(group, groupName) {
  if (group === null || typeof group !== "object" || Array.isArray(group)) {
    throw new ConfigError(`"${groupName}" is missing or not an object in ${SOURCE_FILES.tokens}`);
  }
  const values = [];
  for (const value of Object.values(group)) {
    const match = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
    if (match !== null) values.push(Number(match[1]));
  }
  return values;
}

function tokenNamesOf(tokens) {
  const names = [];
  for (const group of Object.values(tokens)) {
    if (group === null || typeof group !== "object" || Array.isArray(group)) continue;
    for (const name of Object.keys(group)) names.push(name);
  }
  return names.sort(compareStrings);
}

/**
 * Load the allowed values from the generated design source.
 * Throws ConfigError when tokens.json or layers.ts is missing or unreadable.
 */
export function loadDesignSource(root) {
  const tokensText = readSource(root, SOURCE_FILES.tokens);
  let tokens;
  try {
    tokens = JSON.parse(tokensText);
  } catch {
    throw new ConfigError(`${SOURCE_FILES.tokens} is not valid JSON`);
  }
  if (tokens === null || typeof tokens !== "object" || Array.isArray(tokens)) {
    throw new ConfigError(`${SOURCE_FILES.tokens} must contain a JSON object`);
  }

  const spacingValues = pxValues(tokens.spacing, "spacing").sort((a, b) => a - b);
  const positive = spacingValues.filter((value) => value > 0);
  if (positive.length === 0) {
    throw new ConfigError(`no positive px spacing token in ${SOURCE_FILES.tokens}`);
  }
  const grid = Math.min(...positive);

  const layersText = readSource(root, SOURCE_FILES.layers);
  const layers = [...layersText.matchAll(LAYER_ENTRY)].map((match) => ({
    name: match[1],
    order: match[2],
    zIndex: Number(match[3]),
  }));
  if (layers.length === 0) {
    throw new ConfigError(`no layer entries in ${SOURCE_FILES.layers}`);
  }
  const zIndexes = [...new Set(layers.map((layer) => layer.zIndex))].sort((a, b) => a - b);

  const colourNames = Object.keys(tokens.colours ?? {});
  return {
    tokens,
    tokenNames: tokenNamesOf(tokens),
    colourNames,
    spacingValues,
    grid,
    layers,
    zIndexes,
  };
}

const compareStrings = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const toPosix = (path) => path.split("\\").join("/");

/** Whether a path relative to the project root is outside the gate's scope. */
export function isIgnored(relativePath) {
  if (IGNORED_FILES.has(relativePath)) return true;
  const segments = relativePath.split("/");
  const directories = segments.slice(0, -1);
  if (directories.some((segment) => IGNORED_DIRECTORIES.has(segment))) return true;
  const name = segments[segments.length - 1] ?? "";
  return /\.(?:test|spec)\.[^.]+$/i.test(name);
}

function collectFiles(root, absoluteDirectory, files) {
  const entries = readdirSync(absoluteDirectory, { withFileTypes: true }).sort((a, b) =>
    compareStrings(a.name, b.name),
  );
  for (const entry of entries) {
    const absolute = join(absoluteDirectory, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRECTORIES.has(entry.name)) continue;
      collectFiles(root, absolute, files);
      continue;
    }
    if (!entry.isFile()) continue;
    const relativePath = toPosix(relative(root, absolute));
    if (isIgnored(relativePath)) continue;
    if (!SCAN_EXTENSIONS.has(extname(entry.name).toLowerCase())) continue;
    files.push(relativePath);
  }
}

function scanRawColours(file, number, line, findings) {
  const matches = [];
  for (const match of line.matchAll(HEX_COLOUR)) matches.push([match.index ?? 0, match[0]]);
  for (const match of line.matchAll(FUNCTION_COLOUR)) matches.push([match.index ?? 0, match[0]]);
  matches.sort((a, b) => a[0] - b[0]);
  for (const [, value] of matches) {
    findings.push({
      file,
      line: number,
      rule: RULES.RAW_COLOUR,
      message: `raw colour ${value}; use a var(--…) token from ${SOURCE_FILES.tokens} (design rule 2)`,
    });
  }
}

function scanSpacing(file, number, line, source, findings, skipped) {
  for (const match of line.matchAll(SPACING_PROPERTY)) {
    const property = match[0].slice(0, match[0].indexOf(":")).trim().toLowerCase();
    const value = match[2].trim();
    if (value === "") continue;
    const withoutVar = value.replace(/var\([^)]*\)/gi, "");
    if (withoutVar.includes("(")) {
      skipped.push({
        file,
        line: number,
        rule: RULES.OFF_GRID_SPACING,
        property,
        value,
        reason: "function value (calc() etc.)",
      });
      continue;
    }
    for (const rawToken of value.split(/\s+/)) {
      const token = rawToken.replace(/!important$/i, "");
      if (token === "" || /^var\(/i.test(token)) continue;
      if (KEYWORD_VALUE.test(token)) continue;
      if (token.includes("(")) {
        skipped.push({ file, line: number, rule: RULES.OFF_GRID_SPACING, property, value: token, reason: "function value (calc() etc.)" });
        continue;
      }
      if (/%$/.test(token) || NON_PX_UNIT.test(token)) {
        skipped.push({ file, line: number, rule: RULES.OFF_GRID_SPACING, property, value: token, reason: "non-px unit" });
        continue;
      }
      let px = null;
      const pxMatch = /^(-?\d+(?:\.\d+)?)px$/i.exec(token);
      if (pxMatch !== null) px = Number(pxMatch[1]);
      else {
        const unitless = /^(-?(?:\d+(?:\.\d+)?|\.\d+))$/.exec(token);
        if (unitless !== null) px = Number(unitless[1]);
      }
      if (px === null) {
        skipped.push({ file, line: number, rule: RULES.OFF_GRID_SPACING, property, value: token, reason: "unrecognised spacing value" });
        continue;
      }
      const multiple = px / source.grid;
      if (px !== 0 && Math.abs(multiple - Math.round(multiple)) > 1e-9) {
        findings.push({
          file,
          line: number,
          rule: RULES.OFF_GRID_SPACING,
          message: `spacing ${token} on ${property} is not 0 or a multiple of ${source.grid}px; use a var(--space-…) token (design rule 3)`,
        });
      }
    }
  }
}

function scanZIndex(file, number, line, source, findings) {
  for (const match of line.matchAll(Z_INDEX_PROPERTY)) {
    const value = match[1].trim();
    if (value === "" || /^var\(/i.test(value) || !/^-?\d+$/.test(value)) continue;
    if (!source.zIndexes.includes(Number(value))) {
      findings.push({
        file,
        line: number,
        rule: RULES.Z_INDEX,
        message: `z-index ${value} has no layer entry in ${SOURCE_FILES.layers}; allowed layer z-index values: ${source.zIndexes.join(", ")} (design rule 8)`,
      });
    }
  }
}

function checkEvidence(root, task, findings) {
  let names = [];
  try {
    names = readdirSync(join(root, "reviews", "evidence")).sort(compareStrings);
  } catch {
    names = [];
  }
  for (const kind of ["before", "after"]) {
    const expected = `reviews/evidence/${task}-${kind}-*.png`;
    const found = names.some(
      (name) => name.startsWith(`${task}-${kind}-`) && name.endsWith(".png"),
    );
    if (!found) {
      findings.push({
        file: "reviews/evidence",
        line: 0,
        rule: RULES.MISSING_EVIDENCE,
        message: `missing ${expected} (design rule 11)`,
      });
    }
  }
}

const compareFindings = (a, b) =>
  compareStrings(a.file, b.file) ||
  a.line - b.line ||
  compareStrings(a.rule, b.rule) ||
  compareStrings(a.message, b.message);

/**
 * Check a project tree.
 *
 * @param {string} root project root (relative to the process or absolute)
 * @param {{task?: string|null, source?: object}} [options]
 *   task: also require reviews/evidence/<task>-before-*.png and -after-*.png;
 *   source: pre-loaded design source (used by the tests).
 * @returns {{root: string, task: string|null, findings: object[], skipped: object[], summary: object}}
 */
export function checkProject(root, options = {}) {
  const task = options.task ?? null;
  if (!existsSync(root)) {
    throw new ConfigError(`project root ${root} does not exist`);
  }
  const source = options.source ?? loadDesignSource(root);
  const files = [];
  for (const scanRoot of SCAN_ROOTS) {
    const absolute = join(root, scanRoot);
    if (!existsSync(absolute)) continue;
    collectFiles(root, absolute, files);
  }
  const unique = [...new Set(files)].sort(compareStrings);

  const findings = [];
  const skipped = [];
  for (const file of unique) {
    const content = readFileSync(join(root, file), "utf8");
    const lines = content.split(/\r?\n/);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      const number = index + 1;
      scanRawColours(file, number, line, findings);
      scanSpacing(file, number, line, source, findings, skipped);
      scanZIndex(file, number, line, source, findings);
    }
  }
  if (task !== null) checkEvidence(root, task, findings);

  findings.sort(compareFindings);
  skipped.sort(compareFindings);
  return {
    root,
    task,
    findings,
    skipped,
    summary: { files: unique.length, findings: findings.length, skipped: skipped.length },
  };
}

/** One human-readable line per finding: `file:line: rule: message`. */
export function formatFinding(finding) {
  return `${finding.file}:${finding.line}: ${finding.rule}: ${finding.message}`;
}
